"""The data source: ``langcurriculum``, drawn as text and as structure at once.

An episode is a pure function of its seed, which is the property everything
here leans on. It means a train set and an eval set are separated by *seed
range* rather than by a split file, so the two cannot overlap by construction
and an eval set cannot have been trained on. It also means a "dataset" on disk
is only ever a cache: delete it and the same seeds rebuild it byte for byte.

Each record carries both surfaces of one episode — the rendered prompt and the
term graph the renderer was handed — under a shared ``instance_id``. That is
what lets the two tasks in this repo be about the same thing.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Iterator, Sequence

from .graph import Graph, graph_from_json

__all__ = ["Episode", "lesson_ids", "resolve_lessons", "generate", "write_jsonl",
           "read_jsonl", "build_split"]


@dataclass
class Episode:
    """One episode, in both surfaces."""

    lesson_id: str
    seed: int
    instance_id: str
    language: str
    prompt: str
    answer: str
    choices: list[str]
    graph: Graph
    tags: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["graph"] = self.graph.to_dict()
        return d

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "Episode":
        d = dict(d)
        d["graph"] = Graph.from_dict(d["graph"])
        return cls(**d)

    @property
    def text(self) -> str:
        """The string the language-modelling task runs over: the question and
        its answer, joined, so that next-token prediction is at some point
        actually predicting the answer rather than only the question."""
        return f"{self.prompt}\n{self.answer}"


def _lc():
    try:
        import langcurriculum
    except ImportError as e:                                  # pragma: no cover
        raise ImportError(
            "langcurriculum is not installed. `uv sync` installs it from "
            "https://github.com/JacobFV/formal-language-cirriculum") from e
    return langcurriculum


def lesson_ids() -> list[str]:
    """Every lesson that actually generates. One of the 180 is a specification
    the author declined to grade; it raises, and is excluded here rather than
    failing a run halfway through."""
    lc = _lc()
    return [lid for lid in lc.lesson_ids() if lc.get(lid).status == "implemented"]


def resolve_lessons(spec: str | Sequence[str] | None) -> list[str]:
    """Resolve a lesson selector.

    ``None`` or ``"all"`` is every implemented lesson; ``"tag:mathematics"`` and
    ``"cap:binding"`` select by tag and capability; a curriculum id such as
    ``"core170"`` selects that curriculum in its own order; anything else is
    read as a comma-separated list of lesson ids.
    """
    lc = _lc()
    if spec is None or spec == "all":
        return lesson_ids()
    if isinstance(spec, (list, tuple)):
        names = list(spec)
    elif spec.startswith("tag:"):
        names = [L.id for L in lc.by_tag(spec[4:])]
    elif spec.startswith("cap:"):
        names = [L.id for L in lc.by_capability(spec[4:])]
    elif spec in lc.curriculum_ids():
        names = [n.lesson for n in lc.curriculum(spec).linearize()]
    else:
        names = [s.strip() for s in spec.split(",") if s.strip()]
    live = set(lesson_ids())
    missing = [n for n in names if n not in live]
    if missing:
        raise ValueError(f"not generatable lessons: {missing}")
    return names


def generate(lessons: Sequence[str], *, n: int, seed0: int = 0,
             language: str = "english", max_nodes: int = 512,
             on_error: str = "raise") -> Iterator[Episode]:
    """Draw ``n`` episodes of each lesson, starting from ``seed0``.

    Text and structure are generated from the same seed and therefore describe
    the same world. They are generated by two separate calls because the
    library renders and structures separately; the ``instance_id`` on both is
    what certifies they match, and a mismatch raises rather than passing a
    mislabelled pair downstream.
    """
    lc = _lc()
    for lid in lessons:
        L = lc.get(lid)
        for i in range(n):
            seed = seed0 + i
            try:
                ex = L.example(seed, language=language)
                st = L.structured(seed)
            except Exception:
                if on_error == "raise":
                    raise
                continue
            if ex.instance_id != st["instance_id"]:            # pragma: no cover
                raise RuntimeError(
                    f"{lid} seed {seed}: text and structure are different episodes")
            yield Episode(
                lesson_id=lid, seed=seed, instance_id=ex.instance_id,
                language=ex.language, prompt=ex.prompt, answer=ex.answer,
                choices=list(ex.choices),
                graph=graph_from_json(st["observation"], max_nodes=max_nodes),
                tags=list(ex.metadata.get("tags") or []),
            )


def write_jsonl(path: str | Path, episodes: Iterator[Episode] | Sequence[Episode]) -> int:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    with p.open("w", encoding="utf-8") as f:
        for ep in episodes:
            f.write(json.dumps(ep.to_dict(), ensure_ascii=False) + "\n")
            count += 1
    return count


def read_jsonl(path: str | Path) -> list[Episode]:
    with Path(path).open(encoding="utf-8") as f:
        return [Episode.from_dict(json.loads(line)) for line in f if line.strip()]


def build_split(out_dir: str | Path, *, lessons: str | Sequence[str] | None = None,
                n_train: int = 64, n_eval: int = 16, language: str = "english",
                eval_seed0: int = 1_000_000, max_nodes: int = 512) -> dict[str, int]:
    """Materialise a train/eval cache under ``out_dir``.

    ``eval_seed0`` defaults to a million because the training seeds start at
    zero: the two ranges cannot meet unless someone asks for a million episodes
    per lesson, and the manifest records both so the claim is checkable.
    """
    out = Path(out_dir)
    names = resolve_lessons(lessons)
    counts = {
        "train": write_jsonl(out / "train.jsonl",
                             generate(names, n=n_train, seed0=0, language=language,
                                      max_nodes=max_nodes)),
        "eval": write_jsonl(out / "eval.jsonl",
                            generate(names, n=n_eval, seed0=eval_seed0,
                                     language=language, max_nodes=max_nodes)),
    }
    (out / "manifest.json").write_text(json.dumps({
        "lessons": names, "n_lessons": len(names), "n_train": n_train,
        "n_eval": n_eval, "language": language, "train_seed0": 0,
        "eval_seed0": eval_seed0, "max_nodes": max_nodes, "counts": counts,
    }, indent=2), encoding="utf-8")
    return counts

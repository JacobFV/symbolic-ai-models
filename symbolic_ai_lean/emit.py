"""Lean 4 source, for the **outside** conformance oracle.

The value of an oracle is that we did not write it — the same argument that made
WALS worth wiring up and ``symbolic_ai_data`` worth vendoring verbatim. What is
emitted here is the episode's elaborated signature and term as real Lean 4, so a
real ``lean`` can be asked whether our kernel and Lean's agree about what
typechecks.

Three things this is not:

* **It is not in the hot path.** ``notes/decisions/2026-08-14-the-ir-is-a-knob.md``
  rules out a subprocess elaborator inside a sweep, and the gate's cost section
  is why. Nothing here is imported by :mod:`symbolic_ai_lean.gate`.
* **It has not been run.** There is no ``lean`` or ``elan`` on this machine, so
  ``tests/test_lean_emit.py`` checks the shape of the output and *skips* the
  conformance assertion. An emitter validated only against its own author is
  worth exactly what this repo's author-designed controls have been worth, and
  it is labelled accordingly.
* **It is not a claim that the two kernels agree.** That is the assertion the
  skipped test would make.

The encoding is deliberately dull: everything is an ``axiom``, because the
question is whether the *types* fit together, and axioms make that question
decidable without asking Lean to believe anything about the curriculum.
"""

from __future__ import annotations

from symbolic_ai_core.data.term_graph import TermGraph

from .elaborate import Elaboration, elaborate
from .expr import App, Const, Expr, Lit, MVar, Pi, Sort, spine
from .kernel import MetaCtx

__all__ = ["lean_source", "lean_ident"]

_PRELUDE = """\
-- Generated by symbolic_ai_lean.emit. The outside conformance oracle for the
-- `006` line: if real Lean accepts this file, our native kernel and Lean agree
-- about the episode's signature.
namespace SymbolicAI

axiom Nat  : Type
axiom Str  : Type
axiom Chr  : Type
axiom Unit : Type
axiom List : Type → Type
axiom Fld  : String → Type → Type
"""


def lean_ident(name: str) -> str:
    """A Lean identifier for an arbitrary label. Guillemets take anything."""
    return "«" + name.replace("»", "\\»") + "»"


def _render(e: Expr, ctx: MetaCtx, arities: set[tuple[str, int]]) -> str:
    e = ctx.deref(e)
    if isinstance(e, Sort):
        return "Prop" if e.level == 0 else "Type"
    if isinstance(e, MVar):
        return f"M{e.idx}"
    if isinstance(e, Lit):
        return '"' + e.value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(e, Const):
        return e.name
    if isinstance(e, Pi):
        return f"({_render(e.dom, ctx, arities)} → {_render(e.body, ctx, arities)})"
    if isinstance(e, App):
        head, args = spine(e)
        rendered = [_render(a, ctx, arities) for a in args]
        if isinstance(head, Const) and head.name in ("Tup", "Rec"):
            arities.add((head.name, len(args)))
            return "(" + " ".join([f"{head.name}{len(args)}"] + rendered) + ")"
        return "(" + " ".join([_render(head, ctx, arities)] + rendered) + ")"
    return "Unit"                                     # pragma: no cover


def lean_source(g: TermGraph, *, name: str = "episode") -> str:
    """The episode's signature, plus the metavariables it left open, as Lean."""
    elab: Elaboration = elaborate(g, [], mode="open")
    ctx = elab.ctx
    arities: set[tuple[str, int]] = set()
    decls = [(sym, _render(ty, ctx, arities)) for sym, ty in sorted(elab.decl.items())]
    metas = sorted({int(w[1:]) for _, r in decls for w in r.replace("(", " ")
                    .replace(")", " ").split() if w.startswith("M") and w[1:].isdigit()})

    lines = [_PRELUDE]
    for kind, k in sorted(arities):
        lines.append(f"axiom {kind}{k} : " + " → ".join(["Type"] * (k + 1)))
    if arities:
        lines.append("")
    lines.append(f"-- lesson: {name}, {len(g)} nodes, "
                 f"{len(elab.demoted)} symbols the elaborator gave up on")
    for m in metas:
        lines.append(f"axiom M{m} : Type")
    lines.append("")
    for sym, ty in decls:
        lines.append(f"axiom {lean_ident(sym)} : {ty}")
    if elab.demoted:
        lines.append("")
        lines.append("-- demoted (two occurrences demanded incompatible types): "
                     + ", ".join(sorted(elab.demoted)))
    lines.append("")
    lines.append("end SymbolicAI")
    return "\n".join(lines) + "\n"
